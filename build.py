# ------------------------------------------------------------------ the Explorer
EX = os.path.join(HERE, 'explorer')
def read(*p): return open(os.path.join(EX, *p), encoding='utf-8').read()
def b64(*p): return base64.b64encode(open(os.path.join(EX, *p), 'rb').read()).decode('ascii')
def script_safe(js): return js.replace('</script', '<\\/script')   # a literal </script would end the inline block

def tokens_css(tokens):
    """tokens.json (the design system's shape) -> CSS custom properties, light and dark, print always light."""
    def val(v, theme): return v.get(theme, v.get('light')) if isinstance(v, dict) else v
    def css(v):
        m = re.fullmatch(r'\{([A-Za-z0-9_.-]+)\}', str(v)); return 'var(--%s)' % m.group(1) if m else str(v)
    light, dark = [], []
    for fam, f in tokens.items():
        if fam in ('name', 'version', 'type'): continue
        for tok in f['tokens']:
            l, d = css(val(tok['value'], 'light')), css(val(tok['value'], 'dark'))
            light.append('  --%s: %s;' % (tok['name'], l))
            if d != l: dark.append('  --%s: %s;' % (tok['name'], d))
    ty = tokens['type']
    fams = ['  --font-sans: %s;' % ty['families']['sans'], '  --font-mono: %s;' % ty['families']['mono']]
    styles = ['  --%s-size: %s; --%s-lh: %s; --%s-weight: %s;' % (s['name'], s['fontSize'], s['name'], s['lineHeight'], s['name'], s['fontWeight'])
              for g in ty['groups'] for s in g['styles']]
    out = '/* %s — generated by build.py from explorer/design-tokens.json (the design system). Do not edit by hand. */\n' % tokens['name']
    out += ':root {\n' + '\n'.join(fams + light + styles) + '\n}\n'
    out += '@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) {\n' + '\n'.join(dark) + '\n} }\n'
    out += ':root[data-theme="dark"] {\n' + '\n'.join(dark) + '\n}\n'
    out += '@media print { :root, :root[data-theme="dark"] {\n' + '\n'.join(light) + '\n} }\n'
    return out

def font_css(tokens):
    css = []
    for f in tokens['type']['fonts']:
        path = f['file'].split('/', 1)[1]   # fonts/X.woff2 -> X.woff2
        css.append('@font-face { font-family: "%s"; font-weight: %s; font-style: %s; font-display: swap; src: url(data:font/woff2;base64,%s) format("woff2"); }'
                   % (f['family'], f['weight'], f.get('style', 'normal'), b64('fonts', path)))
    return '\n'.join(css)

tokens = json.load(open(os.path.join(EX, 'design-tokens.json'), encoding='utf-8'))
open(os.path.join(EX, 'tokens.css'), 'w', encoding='utf-8').write(tokens_css(tokens))
edata = json.load(open(os.path.join(HERE,'out','explorer-data.json'), encoding='utf-8'))
learner = None
for name in sorted(os.listdir(os.path.join(EX, 'private'))) if os.path.isdir(os.path.join(EX, 'private')) else []:
    if name.lower().endswith('.ttf'): learner = b64('private', name)
assets = json.dumps({'logo': 'data:image/png;base64,' + b64('assets', 'bettws-logo.png'), 'faces': b64('assets', 'faces.png'), 'learnerFont': learner or ''})
print('Explorer: learner font', ('embedded from explorer/private/' if learner else 'not present (explorer/private/ is empty) — the card uses Helvetica'))

shell = read('index.html'); app_css = read('app.css'); app_js = read('app.js'); jspdf = read('vendor', 'jspdf.umd.min.js')
def explorer(variant, out, site):
    d = dict(edata); d['variant'] = variant; d['site'] = site
    head = '<link rel="manifest" href="manifest.webmanifest">\n<link rel="apple-touch-icon" href="icon-180.png">' if site else ''
    h = (shell.replace('__TITLE__', 'Bettws Curriculum Explorer' + (" (Bertie's version)" if variant == 'bertie' else ''))
              .replace('__VERSION__', edata['version']).replace('__BUILT__', edata['built']).replace('__HEAD_EXTRA__', head)
              .replace('__FONT_CSS__', font_css(tokens)).replace('__TOKENS_CSS__', tokens_css(tokens)).replace('__APP_CSS__', app_css)
              .replace('__DATA__', json.dumps(d, ensure_ascii=False).replace('</', '<\\/'))
              .replace('/*__JSPDF__*/', script_safe(jspdf)).replace('__ASSETS__', script_safe(assets)).replace('__APP_JS__', script_safe(app_js)))
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w', encoding='utf-8').write(h); print(out, len(h)//1024, 'KB')

def icons(folder):
    """Home-screen icons: the logo on its white plate, as the design system asks."""
    try:
        from PIL import Image
    except ImportError:
        print('  (Pillow not installed: no icons made)'); return
    logo = Image.open(os.path.join(EX, 'assets', 'bettws-logo.png')).convert('RGBA')
    for size in (180, 192, 512):
        plate = Image.new('RGBA', (size, size), (255, 255, 255, 255))
        inner = int(size * 0.82); w, h = logo.size; sc = min(inner / w, inner / h)
        im = logo.resize((max(1, int(w * sc)), max(1, int(h * sc))), Image.LANCZOS)
        plate.alpha_composite(im, ((size - im.width) // 2, (size - im.height) // 2))
        plate.convert('RGB').save(os.path.join(folder, 'icon-%d.png' % size), optimize=True)

