"""Bake the extracted data into the pages.

    python3 build.py          out/: the two hubs and the two Explorer files (single, self-contained HTML)
    python3 build.py --site   site/: the GitHub Pages copy (hubs, Explorer with its offline files, landing page)

The Explorer is assembled from explorer/: index.html (shell), app.css, app.js, the fonts,
the logo and faces images, jsPDF, and tokens.css generated here from design-tokens.json
(the design system's tokens). Everything is inlined, so each file works offline on its own.
Run extract.py first (and validate.py before that).
"""
